"""Generic Wagtail administration for Django models not needing bespoke workflows.

The project keeps hand-written viewsets for models with special lifecycle rules.
This module covers the remaining application models so the Wagtail admin exposes
one consistent CRUD/inspect surface without duplicating dozens of near-identical
classes.

Generated forms include every editable local field. Fields marked editable=False,
primary keys, and auto-managed timestamps are read-only. Operational/audit models
can be registered as read-only through READ_ONLY_MODELS.
"""
